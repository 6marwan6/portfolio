import { writeFileSync } from "node:fs";
import dagre from "@dagrejs/dagre";
import { projects } from "../src/content";
import { MARGIN, NODE_H, NODE_SEP, NODE_W, RANK_SEP, type GraphLayout } from "../src/content/layout-types";
import { layoutKey, viewSignature } from "../src/content/signature";

/** A simple chain: every node has at most one incoming and one outgoing edge and they form a single path. */
function chainOrder(v: { nodes: { id: string }[]; edges: { from: string; to: string }[] }): string[] | null {
  const outs = new Map<string, string>();
  const ins = new Map<string, string>();
  for (const e of v.edges) {
    if (outs.has(e.from) || ins.has(e.to)) return null;
    outs.set(e.from, e.to);
    ins.set(e.to, e.from);
  }
  const heads = v.nodes.filter((n) => !ins.has(n.id));
  if (heads.length !== 1) return null;
  const order: string[] = [];
  let cur: string | undefined = heads[0]!.id;
  while (cur) {
    order.push(cur);
    cur = outs.get(cur);
  }
  return order.length === v.nodes.length ? order : null;
}

/** Long chains are laid out in a snake (left to right, then right to left) so they fit the stage without shrinking. */
function serpentine(order: string[]): Pick<GraphLayout, "width" | "height" | "nodes"> {
  const k = order.length >= 8 ? 4 : 3;
  const rows = Math.ceil(order.length / k);
  const nodes: GraphLayout["nodes"] = {};
  order.forEach((id, i) => {
    const row = Math.floor(i / k);
    const col = i % k;
    const c = row % 2 === 0 ? col : k - 1 - col;
    nodes[id] = { x: MARGIN + NODE_W / 2 + c * (NODE_W + NODE_SEP), y: MARGIN + NODE_H / 2 + row * (NODE_H + RANK_SEP) };
  });
  return {
    width: k * NODE_W + (k - 1) * NODE_SEP + MARGIN * 2,
    height: MARGIN * 2 + rows * NODE_H + (rows - 1) * RANK_SEP,
    nodes,
  };
}

/** Computes every system-view layout at build time (not at runtime) and writes src/content/layouts.generated.ts. */
const layouts: Record<string, GraphLayout> = {};

for (const p of projects) {
  for (const v of p.views) {
    const chain = v.nodes.length > 5 ? chainOrder(v) : null;
    if (chain) {
      layouts[layoutKey(p.id, v.id)] = { ...serpentine(chain), sig: viewSignature(v) };
      continue;
    }
    const g = new dagre.graphlib.Graph();
    g.setGraph({ rankdir: "TB", nodesep: NODE_SEP, ranksep: RANK_SEP, marginx: MARGIN, marginy: MARGIN });
    g.setDefaultEdgeLabel(() => ({}));
    for (const n of v.nodes) g.setNode(n.id, { width: NODE_W, height: NODE_H });
    for (const e of v.edges) g.setEdge(e.from, e.to);
    dagre.layout(g);
    const graph = g.graph();
    const nodes: GraphLayout["nodes"] = {};
    for (const n of v.nodes) {
      const pos = g.node(n.id);
      nodes[n.id] = { x: Math.round(pos.x), y: Math.round(pos.y) };
    }
    layouts[layoutKey(p.id, v.id)] = { width: Math.ceil(graph.width ?? 0), height: Math.ceil(graph.height ?? 0), sig: viewSignature(v), nodes };
  }
}

const body = `// Generated by scripts/layout-graphs.ts. Do not edit by hand; run \`npm run layout:graphs\`.
import type { GraphLayout } from "./layout-types";

export const layouts: Record<string, GraphLayout> = ${JSON.stringify(layouts, null, 2)};
`;
writeFileSync(new URL("../src/content/layouts.generated.ts", import.meta.url), body);
console.log(`Wrote ${Object.keys(layouts).length} graph layouts.`);
